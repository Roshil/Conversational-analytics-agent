"""Render generated documentation from the schema registry and data manifests.

Run after scripts/generate_data.py:
    python scripts/build_docs.py
Writes docs/data_dictionary.md, docs/sample_records.md, docs/03_defect_catalog.md,
docs/04_evaluation_plan.md and data/manifests/behavioral_eval_cases.json.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402

from analytics_agent import schema_registry as sr  # noqa: E402
from analytics_agent.evaluation_cases import BEHAVIORAL_CASES  # noqa: E402

DOCS, MAN, GEN = ROOT / "docs", ROOT / "data" / "manifests", ROOT / "data" / "generated"


def _md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        out.append("| " + " | ".join("" if pd.isna(v) else str(v).replace("|", "\\|") for v in row) + " |")
    return "\n".join(out)


def sample_records() -> str:
    lines = ["# Sample records (clean dataset)", "",
             "_Generated by `scripts/build_docs.py` from `data/generated/clean/csv`. "
             "`email` is synthetic but is masked here to model PII handling._", ""]
    for name in sr.TABLE_LOAD_ORDER:
        df = pd.read_csv(GEN / "clean" / "csv" / f"{name}.csv", dtype=str, keep_default_na=False, nrows=None if name in ("orders", "payments", "refunds") else 50)
        if name == "orders":   # show variety of statuses
            df = df.groupby("order_status", group_keys=False).head(1)
        elif name == "payments":
            df = df.groupby("payment_status", group_keys=False).head(1)
        elif name == "refunds":
            df = df.groupby("refund_reason", group_keys=False).head(1).head(4)
        else:
            df = df.head(3)
        if "email" in df:
            df["email"] = df["email"].str.replace(r"^[^@]+", "***", regex=True)
        lines += [f"## `{name}`", "", _md_table(df), ""]
    return "\n".join(lines)


def defect_catalog() -> str:
    defects = json.loads((MAN / "defect_catalog.json").read_text())
    legit = json.loads((MAN / "legitimate_cases.json").read_text())
    lines = ["# 03 — Defect catalog (corrupted dataset)", "",
             "_Generated from `data/manifests/defect_catalog.json`. Each order is touched by at most one defect; "
             "expected findings include genuine cascades. A perfect validator reports exactly these findings and nothing else._", "",
             "| ID | Table | Columns | Type | Severity | Affected | Detection rule | Expected findings |",
             "|---|---|---|---|---|---|---|---|"]
    for d in defects:
        findings = "; ".join(f"`{k}`: {len(v)}" for k, v in d["expected_findings"].items())
        lines.append(f"| {d['defect_id']} | `{d['table']}` | {', '.join(d['columns'])} | {d['defect_type']} | "
                     f"{d['severity']} | {d['affected_count']} | `{d['detection_rule']}` | {findings} |")
    lines += [""]
    for d in defects:
        lines += [f"### {d['defect_id']} — {d['defect_type']}", "", f"**What:** {d['description']}", "",
                  f"**Business impact:** {d['business_impact']}", "", f"**Expected outcome:** {d['expected_outcome']}", "",
                  f"**Example affected ids:** {', '.join(map(str, d['affected_ids'][:5]))}", ""]
    lines += ["## Legitimate cases that must NOT be flagged", "", "| Case | Count (clean) | Why it is legitimate |", "|---|---|---|"]
    for c in legit:
        lines.append(f"| {c['case']} | {c['count']} | {c['why_legitimate']} |")
    return "\n".join(lines) + "\n"


def _fmt_result(r) -> str:
    if isinstance(r, list):
        if r and isinstance(r[0], dict):
            keys = list(r[0])
            head = ", ".join(f"{k}={r[0][k]}" for k in keys[:4])
            return f"{len(r)} rows; first: {head}"
        return str(r)
    if isinstance(r, dict):
        if "ranking" in r:
            return f"largest_decline_region={r['largest_decline_region']}"
        return ", ".join(f"{k}={v}" for k, v in list(r.items())[:5])
    return str(r)


def evaluation_plan() -> str:
    exp = json.loads((MAN / "expected_results_clean.json").read_text())
    lines = ["# 04 — Evaluation plan and gold cases", "",
             "_Numeric results generated from `data/manifests/expected_results_clean.json` (independent pandas calculations "
             "in `src/analytics_agent/metrics.py`, never an LLM). Full rows are in the JSON._", "",
             f"Window: {exp['window'][0]} to {exp['window'][1]}; snapshot {exp['as_of']}.", "",
             "## Numeric gold cases", "", "| ID | Question | Category | Grain | Expected result (summary) | Tolerance |",
             "|---|---|---|---|---|---|"]
    for c in exp["cases"]:
        lines.append(f"| {c['test_id']} | {c['question']} | {c['category']} | {c['grain']} | "
                     f"{_fmt_result(c['expected_result'])} | {c['tolerance']} |")
    lines += ["", "## Known wrong answers (reviewer must catch)", "",
              "| ID | Mistake | Wrong value | Correct value | Expected reviewer behaviour |", "|---|---|---|---|---|"]
    for w in exp["known_wrong_answers"]:
        lines.append(f"| {w['id']} | {w['mistake']} | {w['wrong_value']} | {w['correct_value']} | {w['expected_reviewer_behavior']} |")
    lines += ["", "## Behavioural cases", "", "| ID | Category | Question | Expected | Pass criteria |", "|---|---|---|---|---|"]
    for b in BEHAVIORAL_CASES:
        q = b["question"] + (f" → *{b['follow_up']}*" if "follow_up" in b else "")
        lines.append(f"| {b['test_id']} | {b['category']} | {q} | {b['expected_behavior']} | {b['pass_criteria']} |")
    lines += ["", "## Metrics to be measured (Stage 8)", "",
              "SQL execution success; result correctness within tolerance; metric-definition correctness (from SQL properties, "
              "checked deterministically where possible); defect detection rate, precision and false-positive rate against the "
              "defect catalog; reviewer precision/recall on W-cases and seeded bad SQL; answer faithfulness (every number in the "
              "answer appears in result rows); appropriate abstention rate (B06, B08); unauthorized-query rejection rate "
              "(B09–B12); end-to-end success; latency and token cost. Executable SQL and semantically correct SQL are scored "
              "separately. Any LLM-as-judge score is secondary to these deterministic checks.", ""]
    return "\n".join(lines)


def main() -> int:
    if not (MAN / "expected_results_clean.json").exists():
        print("Run scripts/generate_data.py first.")
        return 1
    (DOCS / "data_dictionary.md").write_text(sr.render_data_dictionary_markdown() + "\n")
    (DOCS / "sample_records.md").write_text(sample_records() + "\n")
    (DOCS / "03_defect_catalog.md").write_text(defect_catalog())
    (DOCS / "04_evaluation_plan.md").write_text(evaluation_plan())
    (MAN / "behavioral_eval_cases.json").write_text(json.dumps(BEHAVIORAL_CASES, indent=2) + "\n")
    print("Wrote docs/data_dictionary.md, docs/sample_records.md, docs/03_defect_catalog.md, "
          "docs/04_evaluation_plan.md, data/manifests/behavioral_eval_cases.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
